#!/usr/bin/env python3
"""
plot_endtoend.py -- render the end-to-end LP benchmark CSV as PNG plots.

Reads results_endtoend_tol<tol>.csv (produced by endtoend_build_csv.py)
and writes plots/endtoend_tol<tol>[__<view>].png.

Three views are generated by default:
  * "all"        : cuopt-distributed + D-PDLP + cuopt-base side by side
  * "dpdlp"      : cuopt-distributed vs D-PDLP only
  * "cuopt-base" : cuopt-distributed vs cuopt-base only

Each bar for a converged run is split into two stacked segments:
  - hatched (bottom)  : presolve + setup time  = total - step
  - solid   (top)     : solve-loop time        = step
The full bar height is total wall time. A tag above each bar reports
`total_s` for successful runs, "TIME LIMIT" for time-limit runs, and
"CRASH" for anything else (with the exit code).

Usage:
    python plot_endtoend.py                       # default: tol=1e-4, all 3 views
    python plot_endtoend.py --tol 1e-6
    python plot_endtoend.py --view every          # explicit synonym for "all three"
    python plot_endtoend.py --view dpdlp          # only that PNG
    python plot_endtoend.py --csv path/to.csv --out-dir plots/
"""

from __future__ import annotations

import argparse
import csv
import math
import sys
from dataclasses import dataclass, field
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import matplotlib.patches as mpatches


HERE = Path(__file__).resolve().parent

TIME_LIMIT_S = 3600.0
TIME_LIMIT_TOL = 0.90  # >= 90% of time limit AND has iterations => TIME_LIMIT


# ------------------------------------------------------------------
# Data model
# ------------------------------------------------------------------

@dataclass
class Row:
    solver: str
    instance: str
    n_gpus: int
    total_s: float | None
    setup_s: float | None
    step_s: float | None
    presolve_s: float | None
    iterations: int | None
    status: str
    exit_code: str

    @property
    def pre_s(self) -> float | None:
        """Presolve + setup = total - step. Returns None if unavailable."""
        if self.total_s is None:
            return None
        if self.step_s is None:
            # Fall back to explicit presolve_s + setup_s if step_s is missing.
            parts = [x for x in (self.presolve_s, self.setup_s) if x is not None]
            if not parts:
                return None
            return sum(parts)
        return max(0.0, self.total_s - self.step_s)

    @property
    def loop_s(self) -> float | None:
        """Solve-loop time (= step_s if present, else total - pre)."""
        if self.step_s is not None:
            return self.step_s
        if self.total_s is None or self.pre_s is None:
            return None
        return max(0.0, self.total_s - self.pre_s)

    @property
    def is_time_limit(self) -> bool:
        s = (self.status or "").strip().upper()
        if s in ("TIME_LIMIT", "TIME LIMIT", "TIMELIMIT"):
            return True
        # Fall back to "close to the wall-clock cap with some iterations
        # accumulated" -- covers cuopt-distributed runs that crash on
        # teardown after burning the entire time budget.
        if (self.total_s is not None
            and self.total_s >= TIME_LIMIT_TOL * TIME_LIMIT_S
            and (self.iterations or 0) > 0):
            return True
        return False

    @property
    def is_crash(self) -> bool:
        """Non-zero exit code AND not classifiable as a legitimate
        time-limit run."""
        if self.exit_code in ("", "0", 0):
            return False
        return not self.is_time_limit

    @property
    def is_ok(self) -> bool:
        s = (self.status or "").strip().upper()
        return s in ("OPTIMAL", "SOLVED") and not self.is_crash


def _as_float(x) -> float | None:
    try:
        v = float(x)
        if math.isnan(v):
            return None
        return v
    except (TypeError, ValueError):
        return None


def _as_int(x) -> int | None:
    try:
        return int(float(x))
    except (TypeError, ValueError):
        return None


def load_rows(csv_path: Path) -> list[Row]:
    rows: list[Row] = []
    with csv_path.open("r", newline="") as f:
        rdr = csv.DictReader(f)
        for r in rdr:
            rows.append(Row(
                solver     = r.get("solver", "").strip(),
                instance   = r.get("instance", "").strip(),
                n_gpus     = _as_int(r.get("n_gpus")) or 0,
                total_s    = _as_float(r.get("total_s")),
                setup_s    = _as_float(r.get("setup_s")),
                step_s     = _as_float(r.get("step_s")),
                presolve_s = _as_float(r.get("presolve_s")),
                iterations = _as_int(r.get("iterations")),
                status     = r.get("status", "").strip(),
                exit_code  = str(r.get("exit_code", "")).strip(),
            ))
    return rows


# ------------------------------------------------------------------
# Views: subsets of solvers to compare
# ------------------------------------------------------------------

# Consistent colors across views so the eye tracks the solvers.
COLOR = {
    "cuopt-distributed": "#76B900",  # NVIDIA green
    "dpdlp":             "#1F77B4",  # blue
    "cuopt-base":        "#8B4A9C",  # purple
}
LABEL = {
    "cuopt-distributed": "cuopt-distributed (N=8)",
    "dpdlp":             "D-PDLP (N=8)",
    "cuopt-base":        "cuopt-base (N=1)",
}

VIEWS: dict[str, list[str]] = {
    "all":        ["cuopt-distributed", "dpdlp", "cuopt-base"],
    "dpdlp":      ["cuopt-distributed", "dpdlp"],
    "cuopt-base": ["cuopt-distributed", "cuopt-base"],
}


# ------------------------------------------------------------------
# Plot
# ------------------------------------------------------------------

def _stem(instance: str) -> str:
    """Strip .mps suffix for x-axis labels."""
    if instance.endswith(".mps"):
        return instance[:-4]
    return instance


def _all_instances_sorted(rows: list[Row]) -> list[str]:
    """Return the unique instance list in a stable order: alphabetical
    (case-insensitive) for reproducibility across plot regenerations."""
    seen: set[str] = set()
    out: list[str] = []
    for r in sorted(rows, key=lambda r: r.instance.lower()):
        if r.instance not in seen:
            seen.add(r.instance)
            out.append(r.instance)
    return out


def plot_view(rows: list[Row], view_name: str, out_path: Path, tol: str) -> None:
    solvers = VIEWS[view_name]

    # Filter and group.
    rows = [r for r in rows if r.solver in solvers]
    if not rows:
        print(f"!! plot_view({view_name}): no rows for solvers {solvers}", file=sys.stderr)
        return
    instances = _all_instances_sorted(rows)

    # Layout: instances on x-axis, one bar per solver per instance.
    # x_step controls the horizontal distance between successive instance
    # groups; total_group is the width of each group's bars. The empty
    # space between groups is (x_step - total_group). Tune both to
    # tighten or loosen the plot horizontally.
    n_ins = len(instances)
    n_sol = len(solvers)
    fig_w = max(10.0, 0.55 * n_ins * n_sol + 3.5)
    fig_h = 8.0
    fig, ax = plt.subplots(figsize=(fig_w, fig_h))

    x_step = 0.7                # inter-group distance on x-axis (was 1.0)
    total_group = 0.55          # width of each instance's bar cluster
    bar_w = total_group / n_sol
    xs_base = [i * x_step for i in range(n_ins)]

    # Pre-index rows by (solver, instance) for O(1) lookup.
    by_key: dict[tuple[str, str], Row] = {(r.solver, r.instance): r for r in rows}

    # Ymax = tallest legit bar, with headroom for the labels.
    max_h = 0.0
    for r in rows:
        h = r.total_s if r.total_s is not None else 0.0
        if r.is_time_limit:
            h = TIME_LIMIT_S
        max_h = max(max_h, h)
    y_top = max(max_h * 1.18, TIME_LIMIT_S * 1.05)
    ax.set_ylim(0, y_top)

    # Draw bars.
    for si, solver in enumerate(solvers):
        color = COLOR[solver]
        # Offset within the group so the n_sol bars sit centered on x = i.
        offset = (si - (n_sol - 1) / 2) * bar_w
        for xi, ins in enumerate(instances):
            r = by_key.get((solver, ins))
            x = xs_base[xi] + offset
            if r is None:
                # No data at all -> nothing drawn, tiny "N/A" tag.
                ax.text(x, y_top * 0.02, "N/A", ha="center", va="bottom",
                        fontsize=6, color="#999999", rotation=90)
                continue

            if r.is_crash:
                # Empty red-outline bar with "CRASH" tag; no timing to show.
                ax.bar(x, y_top * 0.02, width=bar_w * 0.9,
                       facecolor="none", edgecolor="#c62828",
                       linewidth=1.5, hatch="//")
                tag = f"CRASH\n(exit={r.exit_code})"
                ax.text(x, y_top * 0.03, tag, ha="center", va="bottom",
                        fontsize=6.5, color="#c62828", rotation=0)
                continue

            if r.is_time_limit:
                # Full-height bar clipped at TIME_LIMIT_S, dashed outline.
                total = TIME_LIMIT_S
                pre = r.pre_s or 0.0
                loop = max(0.0, total - pre)
                if pre > 0:
                    ax.bar(x, pre, width=bar_w * 0.9, color=color,
                           edgecolor="#333", linewidth=0.6, hatch="//",
                           alpha=0.75)
                ax.bar(x, loop, width=bar_w * 0.9, bottom=pre,
                       color=color, edgecolor="#333", linewidth=0.6,
                       linestyle="--")
                ax.text(x, total + y_top * 0.005, "TIME LIMIT",
                        ha="center", va="bottom", fontsize=7,
                        color="#b71c1c", rotation=0)
                continue

            # Regular converged run.
            total = r.total_s or 0.0
            pre = r.pre_s or 0.0
            loop = r.loop_s if r.loop_s is not None else max(0.0, total - pre)
            if pre > 0:
                ax.bar(x, pre, width=bar_w * 0.9, color=color,
                       edgecolor="#333", linewidth=0.6, hatch="//",
                       alpha=0.75)
            ax.bar(x, loop, width=bar_w * 0.9, bottom=pre,
                   color=color, edgecolor="#333", linewidth=0.6)
            ax.text(x, total + y_top * 0.005, f"{total:.1f}s",
                    ha="center", va="bottom", fontsize=7,
                    color="#222", rotation=0)

    # X labels + grid.
    ax.set_xticks(xs_base)
    ax.set_xticklabels([_stem(i) for i in instances],
                       rotation=35, ha="right", fontsize=9)
    ax.set_ylabel("wall-clock time (s)", fontsize=11)
    ax.set_xlabel("instance", fontsize=11)
    ax.grid(axis="y", linestyle=":", alpha=0.5)
    ax.axhline(y=TIME_LIMIT_S, color="#b71c1c", linestyle="--",
               linewidth=0.8, alpha=0.6, label=f"time limit ({TIME_LIMIT_S:.0f}s)")

    # Legend: color per solver + hatch legend "presolve + setup" vs solid "solve loop".
    legend_solver = [
        mpatches.Patch(facecolor=COLOR[s], edgecolor="#333", label=LABEL[s])
        for s in solvers
    ]
    legend_split = [
        mpatches.Patch(facecolor="#cccccc", edgecolor="#333",
                       hatch="//", alpha=0.75, label="presolve + setup"),
        mpatches.Patch(facecolor="#cccccc", edgecolor="#333",
                       label="solve loop"),
    ]
    legend_tl = [
        mpatches.Patch(facecolor="none", edgecolor="#b71c1c",
                       linewidth=1.5, hatch="//",
                       label=f"time limit ({TIME_LIMIT_S:.0f}s)"),
        mpatches.Patch(facecolor="none", edgecolor="#c62828",
                       linewidth=1.5, hatch="//", label="crash"),
    ]
    ax.legend(handles=legend_solver + legend_split + legend_tl,
              loc="upper left", bbox_to_anchor=(1.005, 1.0),
              fontsize=9, framealpha=0.9)

    title = {
        "all":        "End-to-end LP benchmark: cuopt-distributed vs D-PDLP vs cuopt-base",
        "dpdlp":      "End-to-end LP benchmark: cuopt-distributed vs D-PDLP",
        "cuopt-base": "End-to-end LP benchmark: cuopt-distributed vs cuopt-base",
    }[view_name]
    ax.set_title(f"{title}  (tol={tol}, time_limit={TIME_LIMIT_S:.0f}s)",
                 fontsize=12)

    fig.tight_layout()
    out_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_path, dpi=140, bbox_inches="tight")
    plt.close(fig)
    print(f"wrote {out_path}")


def parse_cli() -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--tol", choices=("1e-4", "1e-6"), default="1e-4",
                   help="which results_endtoend_tol<tol>.csv to read.")
    p.add_argument("--csv", default=None,
                   help="explicit path to the CSV (default: derived from --tol).")
    p.add_argument("--out-dir", default=None,
                   help="output directory for PNGs (default: <this dir>/plots).")
    p.add_argument("--view",
                   choices=list(VIEWS) + ["every"], default="every",
                   help="which view to render. 'every' (default) generates all three.")
    return p.parse_args()


def main() -> int:
    args = parse_cli()
    csv_path = Path(args.csv or (HERE / f"results_endtoend_tol{args.tol}.csv"))
    if not csv_path.is_file():
        sys.exit(f"CSV not found: {csv_path}. Run endtoend_build_csv.py --tol {args.tol} first.")
    out_dir = Path(args.out_dir or (HERE / "plots"))
    rows = load_rows(csv_path)

    views = list(VIEWS) if args.view == "every" else [args.view]
    for v in views:
        if v == "all":
            fname = f"endtoend_tol{args.tol}.png"
        elif v == "dpdlp":
            fname = f"endtoend_tol{args.tol}_dpdlp_vs_cudpdlp.png"
        else:  # cuopt-base
            fname = f"endtoend_tol{args.tol}_cuopt_vs_cudpdlp.png"
        plot_view(rows, v, out_dir / fname, tol=args.tol)
    return 0


if __name__ == "__main__":
    sys.exit(main())
